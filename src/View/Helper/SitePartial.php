<?php
namespace AgileThemeTools\View\Helper;

use Laminas\View\Helper\Partial;
use Laminas\View\Model\ModelInterface;
use Laminas\View\View;
use Omeka\View\Helper\Api;

/*
 * An extension of the Laminas Partial view helper. Allows you to provide site-specific versions of a template if
 * they exist. For example, if you have a template path/mytemplate.phtml and are viewing it from a site with the slug
 * “mysite”, then calling $partial('path/mytemplate') will return path/mytemplate-mysite.phtml if it exists, otherwise
 * the requested path/mytemplate.
 */


class SitePartial extends Partial {
  protected $name;

  public function __invoke($name = null, $values = null)
  {
    $this->name = $name;
    if (0 === func_num_args()) {
      return $this;
    }

    // If we were passed only a view model, just render it.
    if ($name instanceof ModelInterface) {
      return $this->getView()->render($name);
    }

    return parent::__invoke($this->getTemplateName(), $values); // TODO: Change the autogenerated stub
  }

  public function getTemplateName() {
    /** @var Laminas\View\Renderer\PhpRenderer $view */
    $view = $this->getView();

    // Get the site slug if it exists
    $siteSlug = $view->plugin('siteHelper')->getSiteSlug();

    if ($siteSlug) {
      $siteName = "{$this->name}-{$siteSlug}";
      // Check to see if the site specific template is valid
      if($view->resolver($siteName)) {
        // Request the site specific template
        return $siteName;
      };
    }

    return $this->name;
  }
}
