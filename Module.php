require __DIR__ . '/vendor/autoload.php';
class Module extends AbstractModule {
  const NAMESPACE = __NAMESPACE__;

  public function init(ModuleManager $moduleManager) {
    $events = $moduleManager->getEventManager();

    // Registering a listener at default priority, 1, which will trigger
    // after the ConfigListener merges config.
    $events->attach(ModuleEvent::EVENT_MERGE_CONFIG, [$this, 'onMergeConfig']);
  }

  public function install(ServiceLocatorInterface $serviceLocator) {
    $this->refuseWithoutRequiredModules($serviceLocator);
    $this->makeSiteThemeSettingTable($serviceLocator);
  }

  /**
   * Omeka does not enforce dependencies between modules, so this module does: it will not install while a module it
   * requires is missing, inactive or too old. The list is config/dependencies.php (see Dependency\DependencyAudit).
   * This module is not loaded while it is being installed, so the class is included by hand.
   */
  protected function refuseWithoutRequiredModules(ServiceLocatorInterface $serviceLocator): void {
    require_once __DIR__ . '/src/Dependency/DependencyAudit.php';
    $audit = new \AgileThemeTools\Dependency\DependencyAudit(
      $serviceLocator->get('Omeka\ModuleManager'),
      $serviceLocator->get('Omeka\Connection'),
      require \AgileThemeTools\Dependency\DependencyAudit::manifestFile()
    );
    $errors = $audit->errors();
    if ($errors) {
      $lines = array_map(fn ($row) => sprintf('%s: %s %s', $row['label'], $row['message'], $row['fix']), $errors);
      throw new \Omeka\Module\Exception\ModuleCannotInstallException(
        'Agile Theme Tools needs these modules first. ' . implode(' ', $lines) // @translate
      );
    }
  }

  /** The module's configuration page shows the modules it depends on and their tested versions. Nothing to save. */
  public function getConfigForm(\Laminas\View\Renderer\PhpRenderer $renderer) {
    return $renderer->agileDependencies();
  }

  public function handleConfigForm(\Laminas\Mvc\Controller\AbstractController $controller) {
    return true;
  }

  public function upgrade($oldVersion, $newVersion, ServiceLocatorInterface $serviceLocator)
  {
    if (Comparator::lessThan($oldVersion, '2.0.0')) {
      $this->makeSiteThemeSettingTable($serviceLocator);
    }

    parent::upgrade($oldVersion, $newVersion, $serviceLocator); // TODO: Change the autogenerated stub
  }

  public function makeSiteThemeSettingTable(ServiceLocatorInterface $serviceLocator) {
    // Update the database with theme settings table
    /** @var Logger $logger */
    $logger = $serviceLocator->get('Omeka\Logger');

    $schemaPath = OMEKA_PATH . '/modules/AgileThemeTools/data/install/site_theme_settings.sql';
    if (!is_readable($schemaPath)) {
      $logger->err("Agile Theme Tools installer cannot find #{$schemaPath} to create Site Theme Settings database table.");
      return;
    }

    $schema = file_get_contents($schemaPath);
    $connection = $serviceLocator->get('Omeka\Connection');

    foreach (explode(';', $schema) as $statement) {
      $statement = trim($statement);
      if ('' === $statement) {
        continue;
      }
      $connection->exec($statement);
    }
  }

  public function onMergeConfig(ModuleEvent $e) {
    $configListener = $e->getConfigListener();
    $config = $configListener->getMergedConfig(false);
    $config['controllers']['invokables']['Search\Controller\IndexController'] = "AgileThemeTools\Controller\AgileSearchIndexController";
    $config['controllers']['invokables']['Omeka\Controller\Site\Item'] = "AgileThemeTools\Controller\AgileItemController";

    $configListener->setMergedConfig($config);
  }

  public function attachListeners(\Laminas\EventManager\SharedEventManagerInterface $sharedEventManager) {
    $sharedEventManager->attach(\Omeka\Form\SettingForm::class, 'form.add_elements', [$this, 'addSettingFormElements']);
    $sharedEventManager->attach(\Omeka\Form\SettingForm::class, 'form.add_input_filters', [$this, 'addSettingFormInputFilters']);

    // Public pages: the module's basic stylesheets for its own templates, when switched on (see Styling\BasicStyles).
    $sharedEventManager->attach('*', 'view.layout', [$this, 'addBasicStyles']);

    // Site settings > Theme styling: the site's custom CSS (see Styling\CustomCss).
    $sharedEventManager->attach(\Omeka\Form\SiteSettingsForm::class, 'form.add_elements', [$this, 'addSiteSettingFormElements']);
    $sharedEventManager->attach(\Omeka\Form\SiteSettingsForm::class, 'form.add_input_filters', [$this, 'addSiteSettingFormInputFilters']);

    // Dashboard and Modules page: what is wrong with the modules this one depends on, when something is.
    $dependencySummary = function (\Laminas\EventManager\Event $event) {
      echo $event->getTarget()->agileDependencies('summary');
    };
    $sharedEventManager->attach('Omeka\Controller\Admin\Index', 'view.browse.before', $dependencySummary);
    $sharedEventManager->attach('Omeka\Controller\Admin\Module', 'view.browse.before', $dependencySummary);

    // Easy Admin > Check and fix: an "Agile modules" group (see Dependency\EasyAdminTasks).
    if (class_exists(\EasyAdmin\Form\CheckAndFixForm::class)) {
      $dependencyTasks = new \AgileThemeTools\Dependency\EasyAdminTasks();
      $sharedEventManager->attach(\EasyAdmin\Form\CheckAndFixForm::class, 'form.add_elements', [$dependencyTasks, 'addFormElements']);
      $sharedEventManager->attach(\EasyAdmin\Form\CheckAndFixForm::class, 'form.add_input_filters', [$dependencyTasks, 'addInputFilters']);
      $sharedEventManager->attach(\EasyAdmin\Controller\Admin\CheckAndFixController::class, 'easyadmin.job', [$dependencyTasks, 'handleJob']);
    }

    // Easy Admin > Check and fix: a "Theme builds" group (see ThemeBuild\EasyAdminTasks). Only when Easy Admin is active.
    if (class_exists(\EasyAdmin\Form\CheckAndFixForm::class)) {
      $tasks = fn () => new \AgileThemeTools\ThemeBuild\EasyAdminTasks($this->getServiceLocator()->get(\AgileThemeTools\ThemeBuild\BuildManager::class));
      $sharedEventManager->attach(\EasyAdmin\Form\CheckAndFixForm::class, 'form.add_elements', fn ($event) => $tasks()->addFormElements($event));
      $sharedEventManager->attach(\EasyAdmin\Form\CheckAndFixForm::class, 'form.add_input_filters', fn ($event) => $tasks()->addInputFilters($event));
      $sharedEventManager->attach(\EasyAdmin\Controller\Admin\CheckAndFixController::class, 'easyadmin.job', fn ($event) => $tasks()->handleJob($event));
    }
  }

  /** view.layout on public pages: append the basic stylesheets unless the theme styles the module's templates itself. */
  public function addBasicStyles(\Laminas\EventManager\Event $event) {
    $view = $event->getTarget();
    if (!$view instanceof \Laminas\View\Renderer\PhpRenderer || !$view->status()->isSiteRequest()) {
      return;
    }
    $services = $this->getServiceLocator();
    $services->get(\AgileThemeTools\Styling\BasicStyles::class)->inject($view, $services->get('Omeka\Site\ThemeManager')->getCurrentTheme());
  }

  /**
   * Global settings: the properties whose values are never linked to search on public pages. One list serves every
   * site, since it rarely differs between them. See AgileSearchHelper::getUnlinkedTerms().
   */
  public function addSettingFormElements(\Laminas\EventManager\Event $event) {
    $settings = $this->getServiceLocator()->get('Omeka\Settings');
    $value = $settings->get(AgileSearchHelper::UNLINKED_TERMS_SETTING);
    /** @var \Omeka\Form\SettingForm $form */
    $form = $event->getTarget();

    $form->setOption('element_groups', ($form->getOption('element_groups') ?: []) + ['agilethemetools_build' => 'Theme styling and builds']); // @translate
    $form->add([
      'name' => \AgileThemeTools\Styling\CustomCss::GLOBAL_SETTING,
      'type' => \AgileThemeTools\Form\Element\CssTextarea::class,
      'options' => [
        'element_group' => 'agilethemetools_build',
        'label' => 'Custom CSS for all sites', // @translate
        'info' => 'Plain CSS loaded on every site after the theme\'s own stylesheets and before each site\'s custom CSS. Use it for rules shared by all sites; site-specific rules belong in the site\'s settings (Theme styling).', // @translate
      ],
      'attributes' => [
        'id' => \AgileThemeTools\Styling\CustomCss::GLOBAL_SETTING,
        'value' => $settings->get(\AgileThemeTools\Styling\CustomCss::GLOBAL_SETTING),
        'placeholder' => "/* Example */\n.item-label {\n    color: var(--colour--2);\n}",
      ],
    ]);
    $form->add([
      'name' => \AgileThemeTools\Styling\BasicStyles::SETTING,
      'type' => \Laminas\Form\Element\Checkbox::class,
      'options' => [
        'element_group' => 'agilethemetools_build',
        'label' => 'Basic styles for the module\'s templates', // @translate
        'info' => 'Load a few small, plain stylesheets on public pages so the module\'s own blocks and item templates are presentable under a theme that is not an Agile one (Omeka\'s default theme, others). Minimal rules, no design. Never loaded for the Agile base themes, which style these templates themselves.', // @translate
      ],
      'attributes' => [
        'id' => \AgileThemeTools\Styling\BasicStyles::SETTING,
        'value' => (bool) $settings->get(\AgileThemeTools\Styling\BasicStyles::SETTING, false),
      ],
    ]);
    $form->add([
      'name' => \AgileThemeTools\ThemeBuild\BuildManager::NODE_PATH_SETTING,
      'type' => 'Text',
      'options' => [
        'element_group' => 'agilethemetools_build',
        'label' => 'Node.js executable', // @translate
        'info' => 'Used to build site themes. Leave empty to use the node found on the web server\'s PATH; set a full path (to node, or to the directory that holds it) when it lives elsewhere, e.g. /usr/local/bin/node.', // @translate
      ],
      'attributes' => [
        'id' => \AgileThemeTools\ThemeBuild\BuildManager::NODE_PATH_SETTING,
        'value' => $settings->get(\AgileThemeTools\ThemeBuild\BuildManager::NODE_PATH_SETTING),
        'placeholder' => '/usr/local/bin/node',
      ],
    ]);

    // Cards: what the card display mode shows (DisplayMode\CardSettings); sites may override each value.
    \AgileThemeTools\DisplayMode\CardSettingsForm::addElements($form, fn ($key) => $settings->get($key), false);

    $form->add([
      'name' => AgileSearchHelper::UNLINKED_TERMS_SETTING,
      'type' => PropertyList::class,
      'options' => [
        'element_group' => 'display',
        'label' => 'Properties not linked to search', // @translate
        'info' => 'On public item pages and cards, values of these properties are not linked to the search page, e.g. titles, descriptions and rights statements. Applies to every site. Linked items and URIs keep their own links.', // @translate
        'empty_label' => 'None selected: every property with a search field links to search.', // @translate
        'sortable' => false,
      ],
      'attributes' => [
        'id' => AgileSearchHelper::UNLINKED_TERMS_SETTING,
        'value' => $value ?? implode(',', AgileSearchHelper::UNLINKED_TERMS_DEFAULT),
      ],
    ]);
  }

  /**
   * The element has no input of its own; without one the form would not return, and so not save, its value.
   */
  public function addSettingFormInputFilters(\Laminas\EventManager\Event $event) {
    $event->getParam('inputFilter')->add([
      'name' => AgileSearchHelper::UNLINKED_TERMS_SETTING,
      'required' => false,
    ]);
    $event->getParam('inputFilter')->add([
      'name' => \AgileThemeTools\ThemeBuild\BuildManager::NODE_PATH_SETTING,
      'required' => false,
      'filters' => [['name' => 'StringTrim']],
    ]);
    $event->getParam('inputFilter')->add([
      'name' => \AgileThemeTools\Styling\CustomCss::GLOBAL_SETTING,
      'required' => false,
    ]);
    $event->getParam('inputFilter')->add([
      'name' => \AgileThemeTools\Styling\BasicStyles::SETTING,
      'required' => false,
    ]);
    \AgileThemeTools\DisplayMode\CardSettingsForm::addInputFilters($event->getParam('inputFilter'));
  }

  /**
   * Site settings: the site's custom CSS, loaded last on that site's pages.
   */
  public function addSiteSettingFormElements(\Laminas\EventManager\Event $event) {
    $services = $this->getServiceLocator();
    /** @var \Omeka\Form\SiteSettingsForm $form */
    $form = $event->getTarget();
    $siteSettings = $services->get('Omeka\Settings\Site');
    $routeMatch = $services->get('Application')->getMvcEvent()->getRouteMatch();
    $siteSlug = $routeMatch?->getParam('site-slug');
    $siteId = null;
    if ($siteSlug) {
      try {
        $siteId = $services->get('Omeka\ApiManager')->read('sites', ['slug' => $siteSlug])->getContent()->id();
      } catch (\Exception $e) {
        $siteId = null;
      }
    }

    $form->setOption('element_groups', ($form->getOption('element_groups') ?: []) + ['agilethemetools_styling' => 'Theme styling']); // @translate
    $form->add([
      'name' => \AgileThemeTools\Styling\CustomCss::SITE_SETTING,
      'type' => \AgileThemeTools\Form\Element\CssTextarea::class,
      'options' => [
        'element_group' => 'agilethemetools_styling',
        'label' => 'Custom CSS for this site', // @translate
        'info' => 'Plain CSS loaded last on this site\'s pages, after the theme\'s stylesheets and the installation-wide custom CSS. It applies immediately; no theme build is needed. The theme\'s CSS variables are listed below the box.', // @translate
        'site_id' => $siteId,
      ],
      'attributes' => [
        'id' => \AgileThemeTools\Styling\CustomCss::SITE_SETTING,
        'value' => $siteSettings->get(\AgileThemeTools\Styling\CustomCss::SITE_SETTING),
        'placeholder' => "/* Example */\n#main-menu {\n    background-color: var(--colour--1);\n}",
      ],
    ]);

    // Cards for this site: each value empty means the installation's setting.
    \AgileThemeTools\DisplayMode\CardSettingsForm::addElements($form, fn ($key) => $siteSettings->get($key), true);
  }

  public function addSiteSettingFormInputFilters(\Laminas\EventManager\Event $event) {
    $event->getParam('inputFilter')->add([
      'name' => \AgileThemeTools\Styling\CustomCss::SITE_SETTING,
      'required' => false,
    ]);
    \AgileThemeTools\DisplayMode\CardSettingsForm::addInputFilters($event->getParam('inputFilter'));
  }

  public function getConfig() {
   return include __DIR__ . '/config/module.config.php';
  }
}
